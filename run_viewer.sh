#!/bin/bash
# ==============================================================================
# MyRobot Jump: 3D GUI 成果展示与键盘遥控一键启动脚本
# ==============================================================================

SCRIPT_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
cd "${SCRIPT_DIR}"

# 1. 激活跳跃专用虚拟环境与依赖库
source "${SCRIPT_DIR}/activate_jump.sh"

# 2. 检查显示器与 X11 变量 (默认使用本机桌面 :1)
if [ -z "$DISPLAY" ]; then
    export DISPLAY=:1
fi

echo "=================================================================="
echo " 正在启动 Isaac Gym 3D 成果交互窗口与键盘遥控车载仪表盘..."
echo " 显示环境 : DISPLAY=${DISPLAY}"
echo " 键盘映射 : "
echo "   [W] / [S]   : 前进 / 后退 (-0.30 ~ +0.50 m/s，平滑加速 0.8 m/s²)"
echo "   [A] / [D]   : 左转 / 右转 (-0.35 ~ +0.35 rad/s，平滑转向 2.0 rad/s²)"
echo "   [Q] / [E]   : 升高 / 降低机身 (0.340 ~ 0.520 m，平滑升降 0.04 m/s)"
echo "   [Space]     : 触发单次跳跃 (平滑刹车归零并恢复0.398m标称高度后起跳)"
echo "   [X]         : 平滑刹车停车 (速度转向归零，平稳切入闭环驻车PI零漂移自平衡)"
echo "   [R]         : 复位机器人到初始状态"
echo "   [ESC]       : 退出演示"
echo " 仪表功能 : 终端 10 Hz 定位刷新姿态、角速度、速度、3D净空、PhysX命令力矩等8大核心状态"
echo " 遥测导出 : 50 Hz 逐帧数据实时写入 viewer_telemetry.csv"
echo " 操作提示 : 既可以在【3D 仿真窗口】聚焦操作，也可以在【终端窗口】直接按键！"
echo "=================================================================="

python "${SCRIPT_DIR}/legged_gym/legged_gym/scripts/teleop_dual.py" "$@"
